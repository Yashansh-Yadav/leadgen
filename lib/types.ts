export type Issue = { code: string; label: string; severity: 'high' | 'medium' | 'low'; evidence?: Record<string, unknown> };
export type Competitor = { name: string; domain: string | null; mentions: number };
export type FitReason = { rule: string; value?: unknown; min?: unknown; max?: unknown };

export type Lead = {
  id: string;
  company_name: string;
  niche: string;
  country: string;
  city: string;
  address: string | null;
  website: string | null;
  website_domain: string | null;
  phone: string | null;
  rating: number | null;
  review_count: number | null;
  google_maps_url: string | null;
  search_rank: number | null;
  search_query: string | null;
  pipeline_stage: string;
  status: string;
  tier: 'A' | 'B' | 'C' | null;
  leak_score: number | null;
  top_leak: string | null;
  leaks: Leak[];
  issues: Issue[];
  fit_pass: boolean | null;
  fit_reasons: FitReason[];
  is_chain: boolean;
  audit: Record<string, unknown> & {
    pagespeed?: Record<string, unknown> | null;
    html?: Record<string, unknown> | null;
  };
  pagespeed_score: number | null;
  screenshot_path: string | null;
  ai_mentions: number | null;
  ai_answers_total: number | null;
  ai_competitors: Competitor[];
  owner_name: string | null;
  owner_email: string | null;
  email_source: string | null;
  email_verified: boolean | null;
  email_verification: Record<string, unknown> | null;
  pitch_subject: string | null;
  pitch_body: string | null;
  pitch_linkedin: string | null;
  audit_slug: string | null;
  last_error: string | null;
  failed_at_stage: string | null;
  attempts: number;
  created_at: string;
  updated_at: string;
  audited_at: string | null;
  scored_at: string | null;
  pitched_at: string | null;
  contacted_at: string | null;
};
